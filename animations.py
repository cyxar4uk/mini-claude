"""
Анимации Клода. Здесь можно рисовать свои!

Как это устроено
----------------
FRAMES     — кадры. Каждый кадр — список строк одинаковой длины, один символ = один пиксель.
             Символы берутся из PALETTE, точка "." — прозрачный пиксель.
ANIMATIONS — анимации: последовательность имён кадров + скорость (кадров в секунду).
             Имя с тильдой ("~dance1") — тот же кадр, отражённый по горизонтали.

Как добавить свою анимацию
--------------------------
1. Скопируй любой кадр в FRAMES, дай ему новое имя и перерисуй пиксели.
2. Добавь запись в ANIMATIONS, например:
       "my_anim": {"frames": ["my1", "my2"], "fps": 4, "loops": 3},
   loops — сколько раз проиграть, когда запускаешь из меню.
   "move": 2 — (необязательно) сдвигать Клода на 2 пикселя за кадр в сторону взгляда.
3. Правый клик по Клоду → «Перезагрузить анимации». Перезапускать не нужно.
   Новая анимация появится в меню «Анимации», а в авто-режиме он будет иногда играть её сам.

Анимации idle, walk, sleep, air, crouch, held, happy, purr, sad, eat, wave, think, sparkle, dance используются поведением питомца —
их можно перерисовать, но не удалять.
"""

